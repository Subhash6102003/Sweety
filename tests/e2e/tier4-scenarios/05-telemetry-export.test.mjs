import { describe, it, before } from 'node:test';
import assert from 'node:assert/strict';
import { ApiClient } from '../helpers/api-client.mjs';
import { CONFIG } from '../config.mjs';
import { domInspector } from '../helpers/dom-inspector.mjs';

describe('Tier 4 — Scenarios: 05 Telemetry Export & HIPAA Compliance', () => {
  let client;
  const historyJsx = domInspector.readClientComponent('pages/ReadingHistory.jsx');
  const settingsJsx = domInspector.readClientComponent('pages/Settings.jsx');

  before(async () => {
    client = new ApiClient(CONFIG.API_URL);
    await client.login(CONFIG.DEMO_USER.email, CONFIG.DEMO_USER.password);
  });

  it('Step 1: Queries live telemetry rows for export payload', async () => {
    const res = await client.get('/api/readings');
    assert.strictEqual(res.status, 200);
    assert.ok(Array.isArray(res.body.readings));
    assert.ok(res.body.readings.length > 0);
  });

  it('Step 2: Validates CSV structure generated by ReadingHistory export engine', () => {
    assert.ok(historyJsx.includes('exportCSV'), 'ReadingHistory must declare exportCSV function');
    assert.ok(historyJsx.includes('Date'), 'CSV headers must include Date');
    assert.ok(historyJsx.includes('Slot'), 'CSV headers must include Slot');
    assert.ok(historyJsx.includes('Value'), 'CSV headers must include Value');
    assert.ok(historyJsx.includes('Created At'), 'CSV headers must include Created At');
  });

  it('Step 3: Simulates CSV row synthesis and validates RFC 4180 delimiter format', async () => {
    const res = await client.get('/api/readings');
    const rows = res.body.readings.slice(0, 5);

    const headers = ['Date', 'Slot', 'Value (mg/dL)', 'Notes', 'Created At'];
    const csvLines = [headers.join(',')];

    for (const r of rows) {
      csvLines.push(`"${r.reading_date}","${r.slot}",${r.value},"${r.notes || ''}","${r.created_at}"`);
    }

    const csvContent = csvLines.join('\n');
    assert.ok(csvContent.startsWith('Date,Slot,Value (mg/dL),Notes,Created At'));
    assert.strictEqual(csvLines.length, rows.length + 1);

    // Verify row delimiters and values
    for (let i = 1; i < csvLines.length; i++) {
      const parts = csvLines[i].split(',');
      assert.strictEqual(parts.length, 5, 'Each CSV row must contain exactly 5 columns');
    }
  });

  it('Step 4: Validates export standards and HIPAA privacy notice in Settings', () => {
    assert.ok(settingsJsx.includes('Export'), 'Settings must include export controls');
    assert.ok(
      settingsJsx.includes('HIPAA') || settingsJsx.includes('Security') || settingsJsx.includes('Privacy'),
      'Settings must provide HIPAA privacy & regulatory notice'
    );
  });
});
